// Writes the agent-ui skill's component catalog from `registry/catalog.mjs`. `scripts/tests/skill.test.mjs` fails
// when the file differs from what this writes, so run `npm run build:skill` after changing a component's entry.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { components } from "../registry/catalog.mjs";
import { manifests } from "../registry/layers/index.mjs";

export const skillDir = new URL("../packages/agent-ui/skills/agent-ui/", import.meta.url);
export const catalogFile = new URL("references/components.md", skillDir);

export const groups = {
  chat: "Chat core",
  composer: "Composer controls",
  steps: "Agent steps and decisions",
  output: "Developer output",
  indicators: "Indicators and notices",
  shell: "Thread and shell",
  ops: "Agent ops",
};

const layerNames = { vue: "Vue", svelte: "Svelte", solid: "Solid" };

/** The layers beyond React and Web Components that don't ship `name` yet. */
const missingLayers = (name) =>
  Object.entries(manifests)
    .filter(([, manifest]) => !manifest.components.includes(name))
    .map(([layer]) => layerNames[layer]);

export function componentCatalog() {
  const lines = [
    "# Components",
    "",
    `<!-- Generated by scripts/build-skill.mjs from registry/catalog.mjs. Don't edit by hand. -->`,
    "",
    `All ${Object.keys(components).length} components, grouped by the job they do. The item is the React name: add \`-web\`, \`-vue\`, \`-svelte\` or \`-solid\` for another layer (\`npx shadcn@latest add @kind-ui/tool-vue\`). Each component's page is \`https://kindui.dev/llms.mdx/docs/agent-ui/components/<item>.md\`.`,
  ];
  for (const [group, title] of Object.entries(groups)) {
    // A group is listed once it has a component.
    if (!Object.values(components).some(({ group: of }) => of === group)) continue;
    lines.push("", `## ${title}`, "", "| Item | Component | Use it when |", "| --- | --- | --- |");
    for (const [name, { title: component, group: of, when }] of Object.entries(components)) {
      if (of !== group) continue;
      const missing = missingLayers(name);
      const note = missing.length ? ` Not yet in ${missing.join(", ")}.` : "";
      lines.push(`| \`${name}\` | ${component} | ${when[0].toUpperCase()}${when.slice(1)}${note} |`);
    }
  }
  return `${lines.join("\n")}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(catalogFile, componentCatalog());
}
